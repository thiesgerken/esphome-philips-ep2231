#pragma once

#include <cstdint>
#include <vector>

// The mainboard drops single messages, so every command is sent repeatedly.
#define MESSAGE_REPETITIONS 5

namespace esphome {
namespace philips_series_2200 {

// Bytes 3-6 identify the machine. This is an EP2231 with a LatteGo and uses
// 01 02 00 03; the inherited table carried the EP2220 value ending in 02. The
// mainboard latches it at power on, so the wrong value left the water and milk
// path configured for a steam wand machine for the whole session -- coffee
// worked, hot water and cappuccino did not, no matter which button was pressed
// afterwards. See protocol.md for the other machines.
//
// The trailing two bytes are a 12-bit checksum whose algorithm is unknown, but
// the map is linear: flipping a message bit always flips the checksum by the
// same fixed amount. All values here were either captured from the display or
// derived from a captured one that way. Captured: pre_power_on,
// power_without_cleaning, power_off, coffee, espresso, hot_water, cappuccino,
// beans, size. Derived: power_with_cleaning, start_stop, aqua_clean,
// calc_clean.

/// @brief first two bytes of every message on either uart
const uint8_t message_header[2] = {0xD5, 0x55};

const std::vector<uint8_t> command_pre_power_on = {
    0xD5, 0x55, 0x0A, 0x01, 0x02, 0x00, 0x03, 0x00, 0x00, 0x00, 0x23, 0x0F};
const std::vector<uint8_t> command_power_with_cleaning = {
    0xD5, 0x55, 0x02, 0x01, 0x02, 0x00, 0x03, 0x00, 0x00, 0x00, 0x15, 0x08};
const std::vector<uint8_t> command_power_without_cleaning = {
    0xD5, 0x55, 0x01, 0x01, 0x02, 0x00, 0x03, 0x00, 0x00, 0x00, 0x08, 0x3A};
const std::vector<uint8_t> command_power_off = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x01, 0x00, 0x00, 0x30, 0x26};

const std::vector<uint8_t> command_press_coffee = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x08, 0x00, 0x00, 0x14, 0x01};
const std::vector<uint8_t> command_press_espresso = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x02, 0x00, 0x00, 0x24, 0x30};
const std::vector<uint8_t> command_press_hot_water = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x04, 0x00, 0x00, 0x0C, 0x1C};
const std::vector<uint8_t> command_press_cappuccino = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x10, 0x00, 0x00, 0x24, 0x3B};
const std::vector<uint8_t> command_press_start_stop = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x00, 0x00, 0x01, 0x34, 0x2F};
const std::vector<uint8_t> command_press_beans = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x00, 0x02, 0x00, 0x24, 0x32};
const std::vector<uint8_t> command_press_size = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x00, 0x04, 0x00, 0x0D, 0x18};
const std::vector<uint8_t> command_press_aqua_clean = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x00, 0x10, 0x00, 0x20, 0x2B};
const std::vector<uint8_t> command_press_calc_clean = {
    0xD5, 0x55, 0x00, 0x01, 0x02, 0x00, 0x03, 0x00, 0x20, 0x00, 0x05, 0x2A};

} // namespace philips_series_2200
} // namespace esphome
